#!/usr/bin/env node
// Pulls reading data from the Hardcover GraphQL API and regenerates
// src/data/hardcoverBooks.ts. Requires HARDCOVER_API_TOKEN in the
// environment. Run via `npm run sync:hardcover`.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HARDCOVER_USERNAME = "schie";
const ENDPOINT = "https://api.hardcover.app/v1/graphql";
const OUTPUT_PATH = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/data/hardcoverBooks.ts",
);

const QUERY = /* GraphQL */ `
  query HardcoverSync($username: citext!) {
    currentlyReading: user_books(
      where: { user: { username: { _eq: $username } }, status_id: { _eq: 2 } }
      order_by: { last_read_date: desc_nulls_last }
      limit: 6
    ) {
      rating
      book {
        title
        slug
        image {
          url
        }
        contributions {
          contribution
          author {
            name
          }
        }
      }
    }
    recentlyFinished: user_books(
      where: {
        user: { username: { _eq: $username } }
        status_id: { _eq: 3 }
        last_read_date: { _is_null: false }
      }
      order_by: { last_read_date: desc_nulls_last }
      limit: 6
    ) {
      rating
      last_read_date
      book {
        title
        slug
        image {
          url
        }
        contributions {
          contribution
          author {
            name
          }
        }
      }
    }
  }
`;

function authorNames(book) {
  const contributions = book.contributions ?? [];
  const primary = contributions.filter((c) => !c.contribution);
  const names = (primary.length > 0 ? primary : contributions).map(
    (c) => c.author?.name,
  );
  return names.filter(Boolean).join(", ");
}

function toBook(userBook) {
  return {
    title: userBook.book.title,
    slug: userBook.book.slug,
    author: authorNames(userBook.book),
    imageUrl: userBook.book.image?.url,
    rating: userBook.rating ?? undefined,
  };
}

async function fetchHardcoverData() {
  const token = process.env.HARDCOVER_API_TOKEN;
  if (!token) {
    throw new Error("HARDCOVER_API_TOKEN is not set");
  }

  const response = await fetch(ENDPOINT, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${token}`,
      "User-Agent": "schie.github.io-hardcover-sync/1.0",
    },
    body: JSON.stringify({
      query: QUERY,
      variables: { username: HARDCOVER_USERNAME },
    }),
  });

  if (!response.ok) {
    throw new Error(
      `Hardcover API request failed: ${response.status} ${response.statusText}`,
    );
  }

  const payload = await response.json();
  if (payload.errors?.length) {
    throw new Error(
      `Hardcover API returned errors: ${JSON.stringify(payload.errors)}`,
    );
  }

  return payload.data;
}

function renderBookLiteral(book) {
  const fields = [
    `title: ${JSON.stringify(book.title)}`,
    `slug: ${JSON.stringify(book.slug)}`,
    `author: ${JSON.stringify(book.author)}`,
  ];
  if (book.imageUrl) fields.push(`imageUrl: ${JSON.stringify(book.imageUrl)}`);
  if (typeof book.rating === "number") fields.push(`rating: ${book.rating}`);
  if (book.finishedDate)
    fields.push(`finishedDate: ${JSON.stringify(book.finishedDate)}`);
  return `  {\n    ${fields.join(",\n    ")},\n  },`;
}

function renderFile({ currentlyReading, recentlyFinished }) {
  const currentlyReadingLiteral =
    currentlyReading.length > 0
      ? currentlyReading.map(renderBookLiteral).join("\n")
      : "";
  const recentlyFinishedLiteral =
    recentlyFinished.length > 0
      ? recentlyFinished.map(renderBookLiteral).join("\n")
      : "";

  return `// Auto-generated by scripts/sync-hardcover.mjs — do not hand-edit.
// Regenerated daily by .github/workflows/hardcover-sync.yml from
// https://hardcover.app/@${HARDCOVER_USERNAME}

export type HardcoverBook = {
  title: string;
  slug: string;
  author: string;
  imageUrl?: string;
  rating?: number;
};

export type FinishedHardcoverBook = HardcoverBook & {
  finishedDate?: string;
};

export const currentlyReading: HardcoverBook[] = [
${currentlyReadingLiteral}
];

export const recentlyFinished: FinishedHardcoverBook[] = [
${recentlyFinishedLiteral}
];
`;
}

async function main() {
  const data = await fetchHardcoverData();

  const currentlyReading = (data.currentlyReading ?? []).map(toBook);
  const recentlyFinished = (data.recentlyFinished ?? []).map((userBook) => ({
    ...toBook(userBook),
    finishedDate: userBook.last_read_date ?? undefined,
  }));

  const contents = renderFile({ currentlyReading, recentlyFinished });

  await writeFile(OUTPUT_PATH, contents, "utf8");
  console.log(
    `Wrote ${currentlyReading.length} currently-reading and ${recentlyFinished.length} recently-finished books to ${OUTPUT_PATH}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
